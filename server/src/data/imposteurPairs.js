// ======================================================================
//  L'Imposteur — la banque de paires
// ======================================================================
// Tout le jeu tient dans ce fichier. Une manche, c'est UNE paire : tout le
// monde reçoit le premier titre, une seule personne reçoit le second — sans
// savoir qu'elle a reçu le second.
//
// ---------------------------------------------- ce qui fait une BONNE paire
// Deux jeux assez proches pour que les indices se ressemblent, assez éloignés
// pour qu'un mot précis trahisse. « Animal Crossing / Tomodachi Life » est le
// mètre-étalon : « village », « voisins », « collecte » marchent pour les deux,
// « Tom Nook » ou « Mii » tuent celui qui le lâche.
//
// Deux façons de rater une paire, et elles sont symétriques :
//   - TROP LOIN (« Tetris / Skyrim ») : le premier mot du piégé le désigne, la
//     manche est finie avant d'avoir commencé, personne ne s'est amusé ;
//   - TROP PROCHE (« Breath of the Wild / Tears of the Kingdom ») : AUCUN mot
//     ne peut distinguer les deux, le vote devient une loterie et le piégé est
//     démasqué au hasard — ce qui est pire, parce que ça a l'air d'être de sa
//     faute.
//
// L'ordre à l'intérieur d'une paire ne veut RIEN dire : la route tire à pile ou
// face lequel des deux titres devient celui de l'imposteur (routes/
// imposteur.js). Sans ça, un habitué finirait par apprendre que le second est
// toujours le titre piégé, et le jeu s'effondre.
//
// Ces titres sont aussi la matière des propositions du « vol » de fin de
// manche : l'imposteur démasqué doit reconnaître le jeu des autres parmi
// quatre titres, et les trois leurres sortent d'ici.
//
